#!/usr/bin/env python3
"""Audit every item id a bot can wear against the server's XML Character.wz (bot-persistence ticket 20).

A bot dressed in an id whose sprite data is missing or broken can crash or disconnect the v83 client
(zmzeng/solomapling-plugin 0.3.1 found such ids the hard way; this follows its validate_bot_config_ids.py /
WzDeepAudit approach, AGPL-3.0, same upstream). Checked here:

  missing    no Character.wz/<slot>/<id>.img.xml at all (hair/face colour variants included)
  info-only  a wearable equip with no sprite action besides `info` (accessories are exempt)
  broken-uol a <uol> link whose relative target does not exist inside the same img

Sources of ids:
  - every wearable equip in Character.wz: BotDecorateEquips/getRandomEquip and the FM shops pick any
    level-appropriate equip, so the whole catalogue is in play; EquipOmitList.yaml is the only filter
  - BotCosmeticPool hair (base +0..+7) and faces (base +0, +100..+800), BeginnerEquip, GenericEquipPool.yaml
    and NXItemPool.yaml (the NX overlay is not filtered by the omit list)

Usage: python3 -I scripts/bot_item_audit.py <path to wz> [--json out.json] [--write-omit]
  --write-omit  rewrites the generated block of EquipOmitList.yaml with every info-only / broken-uol equip
Exit status 1 when any id a bot can actually receive is bad and not yet omitted.
"""
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "java", "soloMapling")
DECOR = os.path.join(SRC, "ArtificialPlayer", "BotDecoratorSystem")
OMIT = os.path.join(SRC, "itemPool", "EquipOmitList.yaml")

# Equip slots whose sprites are drawn on the body. Accessories (face/eye/earring, pendant, belt, medal...)
# often carry no action sprites in v83 and are exempt from info-only, as in the plugin's check.
WEARABLE_PREFIXES = {100, 101, 102, 104, 105, 106, 107, 108, 109, 110} | set(range(130, 135)) | set(range(137, 150)) | {170}
WEARABLE_DIRS = {"Cap", "Coat", "Longcoat", "Pants", "Shoes", "Glove", "Shield", "Cape", "Weapon", "Accessory"}


def index_character_wz(wz):
    """id -> path for every img in Character.wz."""
    found = {}
    root = os.path.join(wz, "Character.wz")
    for slot in os.listdir(root):
        d = os.path.join(root, slot)
        if not os.path.isdir(d):
            continue
        for name in os.listdir(d):
            m = re.fullmatch(r"0*(\d+)\.img\.xml", name)
            if m:
                found[int(m.group(1))] = (slot, os.path.join(d, name))
    return found


def audit_img(path):
    """(has_action, broken_uols) for one img."""
    tree = ET.parse(path)
    top = tree.getroot()
    has_action = any(child.get("name") != "info" for child in top)
    parent = {c: p for p in top.iter() for c in p}
    broken = []
    for uol in top.iter("uol"):
        target = uol.get("value", "")
        node = parent.get(uol)
        ok = node is not None
        for part in target.split("/"):
            if not ok:
                break
            if part in ("", "."):
                continue
            if part == "..":
                node = parent.get(node)
                ok = node is not None
                continue
            node = next((c for c in node if c.get("name") == part), None)
            ok = node is not None
        if not ok:
            broken.append(path_of(uol, parent) + " -> " + target)
    return has_action, broken


def path_of(node, parent):
    names = []
    while node is not None and parent.get(node) is not None:
        names.append(node.get("name", "?"))
        node = parent.get(node)
    return "/".join(reversed(names))


def ints_in(path, pattern=r"\b\d{5,8}\b"):
    with open(path, encoding="utf-8") as f:
        text = re.sub(r"//.*|#.*", "", f.read())
    return {int(x) for x in re.findall(pattern, text)}


def omitted():
    ids = set()
    with open(OMIT, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"\s*-\s*(\d+)", line)
            if m:
                ids.add(int(m.group(1)))
    return ids


BEGIN = "  # >>> generated by scripts/bot_item_audit.py --write-omit (bot-persistence ticket 20)"
END = "  # <<< generated"


def write_omit(report):
    lines = []
    for item_id in sorted(set(report["info_only"]) | set(report["broken_uol"])):
        if item_id in report["broken_uol"]:
            why = "broken-uol " + report["broken_uol"][item_id][0]
        else:
            why = "info-only " + report["info_only"][item_id]
        lines.append(f"  - {item_id} # {why}")
    with open(OMIT, encoding="utf-8") as f:
        text = f.read()
    start, end = text.index(BEGIN), text.index(END)
    text = text[:start] + BEGIN + "\n" + "\n".join(lines) + ("\n" if lines else "") + text[end:]
    with open(OMIT, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    wz = sys.argv[1]
    out_json = sys.argv[sys.argv.index("--json") + 1] if "--json" in sys.argv else None
    imgs = index_character_wz(wz)
    omit = omitted()
    report = {"missing": {}, "info_only": {}, "broken_uol": {}}

    # 1. Hair and faces from the cosmetic pool, every colour variant the code can roll.
    cosmetic = ints_in(os.path.join(DECOR, "BotCosmeticPool.java"))
    hair = sorted(i for i in cosmetic if 30000 <= i <= 49999)
    faces = sorted(i for i in cosmetic if 20000 <= i <= 29999)
    for base in hair:
        for v in range(8):
            if base + v not in imgs:
                report["missing"].setdefault("hair colour (BotCosmeticPool)", []).append(base + v)
    for base in faces:
        for v in [0] + [k * 100 for k in range(1, 9)]:
            if base + v not in imgs:
                report["missing"].setdefault("face colour (BotCosmeticPool)", []).append(base + v)

    # 2. Explicit equip pools.
    pools = {
        "BeginnerEquip.java": ints_in(os.path.join(DECOR, "BeginnerEquip.java"), r"\b1\d{6}\b"),
        "GenericEquipPool.yaml": ints_in(os.path.join(DECOR, "GenericEquipPool.yaml"), r"\b1\d{6}\b"),
        "NXItemPool.yaml": ints_in(os.path.join(DECOR, "NXItemPool.yaml"), r"\b1\d{6}\b"),
    }
    for source, ids in pools.items():
        for i in sorted(ids):
            if i not in imgs:
                report["missing"].setdefault(source, []).append(i)

    # 3. The whole wearable catalogue (getRandomEquip draws from it) plus everything in the pools.
    pooled = set().union(*pools.values())
    checked = 0
    for item_id, (slot, path) in sorted(imgs.items()):
        if not 1000000 <= item_id <= 1999999:
            continue
        prefix = item_id // 10000
        if slot not in WEARABLE_DIRS and item_id not in pooled:
            continue
        checked += 1
        has_action, broken = audit_img(path)
        if not has_action and prefix in WEARABLE_PREFIXES:
            report["info_only"][item_id] = slot
        if broken:
            report["broken_uol"][item_id] = broken[:3] + ([f"... {len(broken) - 3} more"] if len(broken) > 3 else [])

    # Which bad ids can a bot actually receive today?
    nx_or_pool_only = pools["BeginnerEquip.java"]  # fixed starter gear: the omit list does not filter it
    actionable = []
    for kind in ("info_only", "broken_uol"):
        for item_id in report[kind]:
            if item_id in nx_or_pool_only or item_id not in omit:
                actionable.append((item_id, kind, "pool (not filtered by omit list)" if item_id in nx_or_pool_only else "catalogue"))
    actionable += [(i, "missing", src) for src, ids in report["missing"].items() for i in ids]

    print(f"Character.wz imgs: {len(imgs)}, equips checked: {checked}, hair bases: {len(hair)}, face bases: {len(faces)}")
    for src, ids in report["missing"].items():
        print(f"missing ({src}): {len(ids)} -> {ids[:30]}{' ...' if len(ids) > 30 else ''}")
    print(f"info-only wearables: {len(report['info_only'])}")
    print(f"broken-uol equips: {len(report['broken_uol'])}")
    print(f"already omitted: {len([i for i in list(report['info_only']) + list(report['broken_uol']) if i in omit])}")
    print(f"ACTIONABLE (a bot can receive it today): {len(actionable)}")
    for item_id, kind, where in sorted(actionable)[:200]:
        detail = report["broken_uol"].get(item_id, [""])[0] if kind == "broken_uol" else report["info_only"].get(item_id, "")
        print(f"  {item_id} {kind:10} {where}  {detail}")
    if "--write-omit" in sys.argv:
        write_omit(report)
        print("rewrote the generated block of " + OMIT)
    if out_json:
        with open(out_json, "w", encoding="utf-8") as f:
            json.dump({"report": {k: {str(i): v for i, v in d.items()} for k, d in report.items()},
                       "actionable": actionable}, f, indent=1)
    return 1 if actionable else 0


if __name__ == "__main__":
    sys.exit(main())
